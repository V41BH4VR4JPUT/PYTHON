# class and objects in python

class details :
    name = "vaibhav"
    age = 22
    occupation = "student"
    def info(self):
        print("Name : " , self.name , "\nAge : " , self.age , "\nOccupation : " , self.occupation)

obj = details()
obj.name = "Vaishnavi"
obj.age = 23
obj.occupation = "student"
obj.info()
obj2 = details()
obj2.info()
